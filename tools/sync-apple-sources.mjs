#!/usr/bin/env node
// Vendors apple/Sources/FingerPrintChecker into the Flutter and React Native
// wrapper packages. `--check` reports drift without writing anything.
// Usage: node tools/sync-apple-sources.mjs [--check] [--root <dir>]
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const SOURCE_DIR = 'apple/Sources/FingerPrintChecker';
const TARGETS = ['flutter/ios/Classes/FingerPrintChecker', 'react-native/ios/FingerPrintChecker'];
const SOURCE_FILE = 'SOURCE';

function parseArgs(argv) {
  const opts = { check: false, root: resolve(dirname(fileURLToPath(import.meta.url)), '..') };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') opts.check = true;
    else if (argv[i] === '--root' && argv[i + 1]) opts.root = resolve(argv[++i]);
    else throw new Error(`unknown argument: ${argv[i]}`);
  }
  return opts;
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p));
    }
  };
  walk(dir);
  return out;
}

function sync(root) {
  const src = join(root, SOURCE_DIR);
  if (!existsSync(src)) throw new Error(`missing source tree: ${src}`);
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  for (const t of TARGETS) {
    const dest = join(root, t);
    rmSync(dest, { recursive: true, force: true });
    mkdirSync(dest, { recursive: true });
    cpSync(src, dest, { recursive: true });
    writeFileSync(join(dest, SOURCE_FILE), `${commit}\ngenerated by tools/sync-apple-sources.mjs - do not edit\n`);
  }
  console.log(`synced ${TARGETS.length} targets from ${commit}`);
}

function check(root) {
  const src = join(root, SOURCE_DIR);
  const want = listFiles(src);
  const problems = [];
  for (const t of TARGETS) {
    const dest = join(root, t);
    const have = listFiles(dest).filter((f) => f !== SOURCE_FILE);
    for (const f of want) {
      if (!have.includes(f)) problems.push(`missing: ${t}/${f}`);
      else if (!readFileSync(join(src, f)).equals(readFileSync(join(dest, f)))) problems.push(`differs: ${t}/${f}`);
    }
    for (const f of have) if (!want.includes(f)) problems.push(`extra: ${t}/${f}`);
    if (!existsSync(join(dest, SOURCE_FILE))) problems.push(`missing: ${t}/${SOURCE_FILE}`);
  }
  if (problems.length) {
    console.error(problems.join('\n'));
    console.error('vendored iOS sources drifted; run: node tools/sync-apple-sources.mjs');
    return 1;
  }
  console.log('vendored iOS sources match');
  return 0;
}

try {
  const { check: checkMode, root } = parseArgs(process.argv.slice(2));
  if (checkMode) process.exit(check(root));
  sync(root);
} catch (e) {
  console.error(e.message);
  process.exit(2);
}
